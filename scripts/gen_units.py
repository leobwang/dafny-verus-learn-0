#!/usr/bin/env python3
"""gen_units.py — generate the course's verification units from MODULES.toml
(design §14.2 rule 1; DELTAS Δ22, Δ23, Δ27, Δ30, Δ34, Δ45, Δ56).

One unit per (module, language, library tier), for every module whose status
is not `planned`:

  Dafny   dafny/{Q,R}/<ID>_<Name>/{core,std}/dfyconfig.toml
            includes = the unit's own `*.dfy` plus one glob per given layer of
            the module's layer chain, `../../../given/<T>/<layer>_*.dfy` (Δ27;
            a std unit reaches the whole chain, a core unit only the layers
            that need no standard library, Δ34). Every glob must match a file
            (a wrong glob is silent in Dafny, Δ27): the generator reports one
            that matches nothing.
            [options] = dafny/options/<tier>.toml's [options], then each
            [[override]] whose module range holds the module (Δ30: per-unit
            knobs cannot live in module {:options}; Δ45: manual lemma
            induction from Q03 on; Δ56: the resource-limit pin).
  Verus   verus/{q,r}/<id>_<name>/Cargo.toml: one package per module, its
            dependencies vstd (pinned) plus the crate of its tier's layer and
            of every lower layer (Δ22), `build = false`.
            A crate in CRATE_BINS (the capstone crate, Q18: the user's decision
            D16, 2026-10-12; QPLAN §30 Q59) also gets one `[[bin]]` target,
            its command-line tool, whose root (`src/main.rs`) must exist: the
            tool's argument parsing is code outside `verus!`, trusted, and
            built only through `scripts/vcheck --bin` (the pinned `verus
            --compile`; dvl.verus.run_bin). No other crate has a binary.
          verus/Cargo.toml: the workspace. members = the layer crates those
            modules reach plus the module crates; default-members = the Q
            ones, so a bare `cargo verus verify` builds Q and R is built by
            name (Δ23). The reference crates are never members: they live in
            Solutions/verus/ with their own [workspace].

Units are derived from a module's `exercises` paths (derive_units), the same
function the checker uses to validate the registry's `units` field. Exits,
agent files and specimens are never units (spec §3.1 rule 2). Q19–Q33 build
under Challenges/ through their gate and get no generated unit.

With every module planned, the only output is the empty workspace.

Usage:
  python3 scripts/gen_units.py [--root DIR]            write the units
  python3 scripts/gen_units.py --check [--root DIR]    compare with the tree
  python3 scripts/gen_units.py --list [--json] [--root DIR]
Exit: 0 ok (or no drift); 1 an error, or drift under --check (paths only are
printed, never content); 2 usage.
"""

import argparse
import json
import re
import sys
import tomllib
from pathlib import Path, PurePosixPath

DEFAULT_ROOT = Path(__file__).resolve().parent.parent
REGISTRY = "MODULES.toml"
OPTIONS_DIR = "dafny/options"
WORKSPACE = "verus/Cargo.toml"
VSTD = "=0.0.0-2026-09-20-0158"          # VERSIONS.md §1.2 (cargo verus toolchain list)
DAFNY_RESOURCE_LIMIT = 5000000           # Δ56, the course pin
DAFNY_TIERS = ("core", "std")
HEADER = ("# GENERATED by scripts/gen_units.py from MODULES.toml{extra}. Do not edit:\n"
          "# change the registry or the options file, then run `python3 scripts/gen_units.py`\n"
          "# (`--check` compares; CI's units group runs it).\n")

# The binary targets of module crates (D16, 2026-10-12; QPLAN §28.3 step 6, §30 Q59):
# module id -> (binary name, root file relative to the crate). Only the capstone.
CRATE_BINS = {"Q18": ("bignat", "src/main.rs")}

# --- spine layers (design §10.1, §10.2) ----------------------------------------
# Q: BigNat L1–L7; R: regex A1, A1b, A2–A5 (A1b: the band-1 facts R06 declares, PLAN.md
# §2.2-§2.4, adopted DV5a). Each layer is one Dafny file group
# dafny/given/<T>/<prefix><layer>_*.dfy and one Verus crate verus/given/<crate>.
Q_LAYERS = tuple(f"L{k}" for k in range(1, 8))
R_LAYERS = ("A1", "A1b", "A2", "A3", "A4", "A5")
# The library tier a layer's Dafny files need: L3 and L4 import Std (Δ34), and
# L5–L7 build on L4. The R layers are core until DVR0 shows otherwise.
LAYER_DAFNY_TIER = {**dict.fromkeys(("L1", "L2"), "core"),
                    **dict.fromkeys(("L3", "L4", "L5", "L6", "L7"), "std"),
                    **dict.fromkeys(R_LAYERS, "core")}
# module id -> its layer, fixed by the id (design §10.1, §10.2)
Q_LAYER_RANGES = (("L1", 1, 1), ("L2", 2, 3), ("L3", 4, 6), ("L4", 7, 9), ("L5", 10, 12),
                  ("L6", 13, 15), ("L7", 16, 18))
R_LAYER_RANGES = (("A1", 2, 5), ("A1b", 6, 6), ("A2", 7, 8), ("A3", 9, 9), ("A4", 10, 15),
                  ("A5", 16, 16))


def expected_layer(mid):
    n = int(mid[1:])
    ranges = Q_LAYER_RANGES if mid[0] == "Q" else R_LAYER_RANGES
    return next((layer for layer, lo, hi in ranges if lo <= n <= hi), "")


def layer_first_module(layer):
    """The first module of a layer's range: it declares the layer's files."""
    ranges = Q_LAYER_RANGES if layer.startswith("L") else R_LAYER_RANGES
    lo = next(lo for name, lo, _ in ranges if name == layer)
    return f"{'Q' if layer.startswith('L') else 'R'}{lo:02d}"


def layer_track(layer):
    return "Q" if layer.startswith("L") else "R"


def layer_chain(layer):
    """The layer and every lower layer of its track, lowest first."""
    if not layer:
        return ()
    layers = Q_LAYERS if layer_track(layer) == "Q" else R_LAYERS
    return layers[:layers.index(layer) + 1]


def layer_rank(layer):
    """The layer's position in its track's chain, from 1 (A1b ranks between A1 and A2)."""
    layers = Q_LAYERS if layer_track(layer) == "Q" else R_LAYERS
    return layers.index(layer) + 1


def dafny_layer_prefix(layer):
    return f"QG_{layer}_" if layer_track(layer) == "Q" else f"RG_{layer}_"


def dafny_layer_glob(layer):
    return f"{dafny_layer_prefix(layer)}*.dfy"


def dafny_given_dir(track):
    return f"dafny/given/{track}"


def verus_layer_crate(layer):
    return f"qg_bignat_{layer.lower()}" if layer_track(layer) == "Q" else f"rg_re_{layer.lower()}"


def verus_given_crate_dir(layer):
    return f"verus/given/{verus_layer_crate(layer)}"


GIVEN_CRATE = re.compile(r"qg_bignat_l([1-7])|rg_re_a(1b|[1-5])")


def crate_layer(name):
    """The layer of a given crate name, or None."""
    m = GIVEN_CRATE.fullmatch(name)
    if not m:
        return None
    return f"L{m.group(1)}" if m.group(1) else f"A{m.group(2)}"


# --- units ----------------------------------------------------------------------

DAFNY_UNIT = re.compile(r"(dafny/([QR])/([QR]\d\d)_([A-Za-z0-9]+)/(core|std))/.+")
VERUS_UNIT = re.compile(r"(verus/([qr])/([qr]\d\d)_([a-z0-9]+(?:_[a-z0-9]+)*))/src/.+")


def derive_units(exercises):
    """The verification units a module's exercise paths live in, in canonical
    order: Dafny core, Dafny std, then the Verus crate."""
    dafny, verus = set(), set()
    for p in exercises:
        if m := DAFNY_UNIT.fullmatch(p):
            dafny.add((DAFNY_TIERS.index(m.group(5)), m.group(1)))
        elif m := VERUS_UNIT.fullmatch(p):
            verus.add(m.group(1))
    return [u for _, u in sorted(dafny)] + sorted(verus)


def unit_kind(unit):
    """('d', tier) or ('v', crate) for a unit path."""
    if m := re.fullmatch(r"dafny/[QR]/[^/]+/(core|std)", unit):
        return "d", m.group(1)
    return "v", PurePosixPath(unit).name


# --- options files ----------------------------------------------------------------

# Unit-level knobs a generated project may set (Δ30 lists the knobs that must
# live in the project, not in module {:options}; Δ34, Δ45, Δ56 set three).
ALLOWED_OPTIONS = {"resource-limit": int, "standard-libraries": bool,
                   "manual-lemma-induction": bool, "disable-nonlinear-arithmetic": bool,
                   "isolate-assertions": bool}
# Never in a project: the gate refuses them (Δ10), they silence holes (Δ6, G21),
# or they unbound or bypass verification (Δ10, Δ17).
REFUSED_OPTIONS = {"base", "solver-path", "library", "plugin", "allow-warnings",
                   "allow-axioms", "verification-time-limit", "boogie", "no-verify",
                   "filter-symbol", "filter-position", "solver-option", "solver-log",
                   "bprint", "print", "rprint", "pprint", "includes", "excludes"}
RANGE = re.compile(r"([QR])(\d\d)-([QR])(\d\d)")


def in_range(rng, mid):
    m = RANGE.fullmatch(rng)
    return bool(m) and mid[0] == m.group(1) and int(m.group(2)) <= int(mid[1:]) <= int(m.group(4))


def load_options(root):
    """{tier: (options, [(range, options)])} from dafny/options/<tier>.toml,
    plus error strings. Every tier file is required."""
    out, errs = {}, []
    for tier in DAFNY_TIERS:
        rel = f"{OPTIONS_DIR}/{tier}.toml"
        try:
            with open(root / rel, "rb") as f:
                data = tomllib.load(f)
        except FileNotFoundError:
            errs.append(f"{rel}: not found (the Dafny [options] of every {tier}-tier unit)")
            continue
        except tomllib.TOMLDecodeError as e:
            errs.append(f"{rel}: not valid TOML: {e}")
            continue
        for key in data:
            if key not in ("options", "override"):
                errs.append(f"{rel}: unknown top-level key '{key}' (only [options] and "
                            "[[override]])")
        base = data.get("options")
        if not isinstance(base, dict):
            errs.append(f"{rel}: no [options] table")
            base = {}
        errs += [f"{rel}: [options]: {e}" for e in option_errors(base)]
        if base.get("resource-limit") != DAFNY_RESOURCE_LIMIT:
            errs.append(f"{rel}: [options] resource-limit must be the course pin "
                        f"{DAFNY_RESOURCE_LIMIT} (Δ56)")
        stdlib = base.get("standard-libraries", False)
        if (tier == "std") != (stdlib is True):
            errs.append(f"{rel}: [options] standard-libraries must be "
                        f"{'true' if tier == 'std' else 'absent or false'} in the {tier} tier (Δ34)")
        overrides = []
        raw = data.get("override", [])
        if not isinstance(raw, list) or not all(isinstance(o, dict) for o in raw):
            errs.append(f"{rel}: override must be [[override]] tables")
            raw = []
        for k, o in enumerate(raw, 1):
            if set(o) != {"modules", "options"}:
                errs.append(f"{rel}: override {k}: keys must be exactly modules, options")
                continue
            rng, opts = o["modules"], o["options"]
            m = RANGE.fullmatch(rng) if isinstance(rng, str) else None
            if not m or m.group(1) != m.group(3) or int(m.group(2)) > int(m.group(4)):
                errs.append(f"{rel}: override {k}: modules must be a range like Q03-Q18 "
                            "within one track")
                continue
            if not isinstance(opts, dict) or not opts:
                errs.append(f"{rel}: override {k}: options must be a non-empty table")
                continue
            e = option_errors(opts)
            errs += [f"{rel}: override {k}: {x}" for x in e]
            if "standard-libraries" in opts or "resource-limit" in opts:
                errs.append(f"{rel}: override {k}: standard-libraries and resource-limit are "
                            "tier-wide; an override may not change them")
            if not e:
                overrides.append((rng, opts))
        out[tier] = (base, overrides)
    return out, errs


def option_errors(opts):
    errs = []
    for key, value in opts.items():
        if key in REFUSED_OPTIONS:
            errs.append(f"'{key}' is refused in a course project (the gate refuses it, or it "
                        "silences holes or unbounds verification: Δ6, Δ10, Δ17)")
        elif key not in ALLOWED_OPTIONS:
            errs.append(f"'{key}' is not an allowed unit option (" + ", ".join(ALLOWED_OPTIONS)
                        + ")")
        elif not isinstance(value, ALLOWED_OPTIONS[key]) or (
                ALLOWED_OPTIONS[key] is int and isinstance(value, bool)):
            errs.append(f"'{key}' must be {'an integer' if ALLOWED_OPTIONS[key] is int else 'a boolean'}")
    return errs


def unit_options(options, tier, mid):
    base, overrides = options[tier]
    out = dict(base)
    for rng, opts in overrides:
        if in_range(rng, mid):
            out.update(opts)
    return out


# --- rendering ----------------------------------------------------------------------

def toml_value(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    return json.dumps(v, ensure_ascii=False)


def toml_list(items):
    return "[" + ", ".join(toml_value(x) for x in items) + "]"


def render_dfyconfig(mid, tier, includes, options):
    out = HEADER.format(extra=f" and {OPTIONS_DIR}/{tier}.toml")
    out += f"# Unit: {mid}, Dafny, {tier} tier.\n"
    out += f"includes = {toml_list(includes)}\n\n[options]\n"
    out += "".join(f"{k} = {toml_value(v)}\n" for k, v in options.items())
    return out


def render_crate(mid, crate, layer):
    out = HEADER.format(extra="")
    out += f"# Unit: {mid}, Verus. Dependencies: vstd and the layer chain "
    out += (f"{layer_chain(layer)[0]}–{layer}" if len(layer_chain(layer)) > 1 else layer or "none")
    out += " (Δ22).\n"
    out += ("[package]\n"
            f"name = \"{crate}\"\n"
            "version = \"0.1.0\"\n"
            "edition = \"2021\"\n"
            "publish = false\n"
            "build = false\n\n"
            "[lib]\n"
            "path = \"src/lib.rs\"\n\n")
    if mid in CRATE_BINS:
        name, path = CRATE_BINS[mid]
        out += ("# The command-line tool (D16): code outside verus!, trusted; built and run only by\n"
                "# `scripts/vcheck --bin <this crate> -- <arguments>`.\n"
                "[[bin]]\n"
                f"name = \"{name}\"\n"
                f"path = \"{path}\"\n\n")
    out += ("[dependencies]\n"
            f"vstd = \"{VSTD}\"\n")
    for l in layer_chain(layer):
        c = verus_layer_crate(l)
        out += f"{c} = {{ path = \"../../given/{c}\" }}\n"
    out += "\n[package.metadata.verus]\nverify = true\n"
    return out


def render_workspace(members, default_members):
    out = HEADER.format(extra="")
    out += ("# The Verus workspace: the given layer crates the non-planned modules reach\n"
            "# and one crate per module. default-members = the Q crates, so a bare\n"
            "# `cargo verus verify` builds the Q track and R is built by name (Δ23). The\n"
            "# reference crates live in Solutions/verus/ (their own [workspace]) and are\n"
            "# never members.\n"
            "[workspace]\n"
            "resolver = \"2\"\n")
    out += f"members = {toml_list(members)}\n"
    if default_members:
        out += f"default-members = {toml_list(default_members)}\n"
    return out


# --- planning -----------------------------------------------------------------------

def load_registry(root):
    try:
        with open(root / REGISTRY, "rb") as f:
            return tomllib.load(f), None
    except FileNotFoundError:
        return None, f"{REGISTRY} not found under {root}"
    except tomllib.TOMLDecodeError as e:
        return None, f"{REGISTRY}: not valid TOML: {e}"


def usable(m):
    """True when a record has the fields the generator reads, well typed."""
    return (isinstance(m, dict) and isinstance(m.get("id"), str)
            and re.fullmatch(r"[QR]\d\d", m["id"]) is not None
            and isinstance(m.get("status"), str) and isinstance(m.get("layer"), str)
            and isinstance(m.get("exercises"), list)
            and all(isinstance(x, str) for x in m["exercises"]))


def plan(root, data):
    """(files {rel: content}, units [records], errors) for the registry `data`."""
    options, errs = load_options(root)
    files, units = {}, []
    q_members, r_members = [], []
    layer_crates = {"Q": [], "R": []}
    modules = data.get("module") if isinstance(data.get("module"), list) else []
    for m in modules:
        if not usable(m) or m["status"] == "planned":
            continue
        mid, layer = m["id"], m["layer"]
        if layer and (layer not in LAYER_DAFNY_TIER or layer_track(layer) != mid[0]):
            errs.append(f"{mid}: layer {layer!r} is not a {mid[0]} spine layer; no unit generated")
            continue
        shipped = m["status"] == "shipped"
        for unit in derive_units(m["exercises"]):
            lang, what = unit_kind(unit)
            if lang == "d":
                tier = what
                if tier not in options:
                    continue  # the options file error is already reported
                chain = [l for l in layer_chain(layer)
                         if tier == "std" or LAYER_DAFNY_TIER[l] == "core"]
                track = mid[0]
                includes = ["*.dfy"] + [f"../../../given/{track}/{dafny_layer_glob(l)}"
                                        for l in chain]
                own = sorted(p.name for p in (root / unit).glob("*.dfy")) if (root / unit).is_dir() else []
                if own or shipped:
                    if not own:
                        errs.append(f"{unit}: includes glob '*.dfy' matches no file (Δ27)")
                    for l in chain:
                        d = root / dafny_given_dir(track)
                        if not (d.is_dir() and any(d.glob(dafny_layer_glob(l)))):
                            errs.append(f"{unit}: includes glob '../../../given/{track}/"
                                        f"{dafny_layer_glob(l)}' matches no file (Δ27: a glob "
                                        "that matches nothing is silent in Dafny)")
                files[f"{unit}/dfyconfig.toml"] = render_dfyconfig(
                    mid, tier, includes, unit_options(options, tier, mid))
                units.append({"module": mid, "lang": "d", "tier": tier, "unit": unit,
                              "config": f"{unit}/dfyconfig.toml", "includes": includes})
            else:
                crate = what
                has_src = (root / unit / "src").is_dir() and any((root / unit / "src").rglob("*.rs"))
                if has_src or shipped:
                    for l in layer_chain(layer):
                        if not (root / verus_given_crate_dir(l) / "Cargo.toml").is_file():
                            errs.append(f"{unit}: its layer crate {verus_given_crate_dir(l)} "
                                        "does not exist (Δ22: the module depends on the chain)")
                    if mid in CRATE_BINS and not (root / unit / CRATE_BINS[mid][1]).is_file():
                        errs.append(f"{unit}: its binary target's root {CRATE_BINS[mid][1]} does "
                                    "not exist (D16: the [[bin]] target needs it)")
                files[f"{unit}/Cargo.toml"] = render_crate(mid, crate, layer)
                deps = [verus_layer_crate(l) for l in layer_chain(layer)]
                units.append({"module": mid, "lang": "v", "tier": "", "unit": unit,
                              "config": f"{unit}/Cargo.toml", "dependencies": ["vstd"] + deps})
                rel = PurePosixPath(unit).relative_to("verus").as_posix()
                (q_members if mid[0] == "Q" else r_members).append(rel)
                for l in layer_chain(layer):
                    g = f"given/{verus_layer_crate(l)}"
                    if g not in layer_crates[mid[0]]:
                        layer_crates[mid[0]].append(g)
    key = lambda g: layer_rank(crate_layer(PurePosixPath(g).name))
    q_side = sorted(layer_crates["Q"], key=key) + q_members
    r_side = sorted(layer_crates["R"], key=key) + r_members
    files[WORKSPACE] = render_workspace(q_side + r_side, q_side)
    return files, units, errs


def stale_and_forbidden(root, files):
    """Generated-looking files no unit produces (Δ20: unknown Cargo.toml files
    in learner trees), plus build-tool files that never belong there."""
    errs = []
    for track in ("Q", "R"):
        d = root / "dafny" / track
        if d.is_dir():
            for p in sorted(d.rglob("dfyconfig.toml")):
                rel = p.relative_to(root).as_posix()
                if rel not in files:
                    errs.append(f"{rel}: stale project file — no non-planned unit produces it "
                                "(delete it, or arm its module)")
    for track in ("q", "r"):
        d = root / "verus" / track
        if not d.is_dir():
            continue
        for p in sorted(d.rglob("Cargo.toml")):
            rel = p.relative_to(root).as_posix()
            if rel not in files:
                errs.append(f"{rel}: unknown Cargo.toml in a learner tree — only generated "
                            "module crates live here (Δ20)")
        for p in sorted(d.rglob("build.rs")):
            errs.append(f"{p.relative_to(root).as_posix()}: build scripts never belong in a "
                        "learner crate (build-tool poisoning; crates set build = false)")
        for p in sorted(d.rglob(".cargo")):
            errs.append(f"{p.relative_to(root).as_posix()}: a .cargo directory in a learner "
                        "tree changes what cargo runs (build-tool poisoning)")
    return errs


def check(root, data=None):
    """(errors, units): drift between the generator's output and the tree.
    `data` is the parsed registry (loaded when None)."""
    if data is None:
        data, err = load_registry(root)
        if err:
            return [err], []
    files, units, errs = plan(root, data)
    for rel, content in sorted(files.items()):
        p = root / rel
        if not p.is_file():
            errs.append(f"{rel}: missing — run python3 scripts/gen_units.py")
        elif p.read_text(encoding="utf-8") != content:
            errs.append(f"{rel}: differs from the generator's output — run "
                        "python3 scripts/gen_units.py (never edit a generated file)")
    errs += stale_and_forbidden(root, files)
    return errs, units


def write(root, data):
    files, units, errs = plan(root, data)
    top = root.resolve()
    written = 0
    for rel, content in sorted(files.items()):
        target = root / rel
        if not target.resolve().is_relative_to(top) or target.is_symlink():
            errs.append(f"{rel}: refusing to write through a symlink that leaves {root}")
            continue
        if target.is_file() and target.read_text(encoding="utf-8") == content:
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
        written += 1
        print(f"gen_units: wrote {rel}")
    errs += stale_and_forbidden(root, files)
    return errs, written, units


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate the verification units from MODULES.toml.")
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="compare with the tree; write nothing")
    mode.add_argument("--list", action="store_true", help="print the units; write nothing")
    ap.add_argument("--json", action="store_true", help="with --list: one JSON array")
    ap.add_argument("--root", type=Path, default=DEFAULT_ROOT,
                    help="repo root (default: this script's repo)")
    args = ap.parse_args(argv)
    if args.json and not args.list:
        ap.error("--json goes with --list")
    data, err = load_registry(args.root)
    if err:
        print(err, file=sys.stderr)
        return 1
    if args.list:
        files, units, errs = plan(args.root, data)
        for e in errs:
            print(e, file=sys.stderr)
        if args.json:
            print(json.dumps(units, ensure_ascii=False))
        else:
            for u in units:
                print(f"{u['module']}\t{u['lang']}\t{u['tier'] or '-'}\t{u['config']}")
        return 1 if errs else 0
    if args.check:
        errs, units = check(args.root, data)
        for e in errs:
            print(e)
        if errs:
            print(f"\ngen_units: {len(errs)} problem(s)")
            return 1
        print(f"gen_units: {len(units)} unit(s) and {WORKSPACE} match the registry")
        return 0
    errs, written, units = write(args.root, data)
    for e in errs:
        print(e, file=sys.stderr)
    print(f"gen_units: {len(units)} unit(s); {written} file(s) written")
    return 1 if errs else 0


if __name__ == "__main__":
    sys.exit(main())
